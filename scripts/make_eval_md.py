"""Generate eval_P1_<TeamID>.md from results/<split>/summary.csv (no hand-edited numbers).

Usage: python scripts/make_eval_md.py --team T01 --usns "1XX22CS001" [--splits test_lol test_lolv2]

Metric order follows the problem statement:
PSNR, SSIM, LPIPS, NIQE, Latency, Noise suppression / Edge preservation.
"""
import argparse
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
COLS = [("psnr", "PSNR (dB) ↑", 2), ("ssim", "SSIM ↑", 4), ("lpips", "LPIPS ↓", 4), ("niqe", "NIQE ↓", 3),
        ("latency_ms", "Latency (ms/img, CPU) ↓", 0), ("noise_sigma", "Residual noise σ ↓", 4),
        ("edge_corr", "Edge corr ↑", 4), ("edge_f1", "Edge F1 ↑", 4)]
MAIN = ["input (no enhancement)", "classical (fixed params)", "classical (adaptive)", "DL: Zero-DCE++ pretrained",
        "DL: Zero-DCE++ fine-tuned", "hybrid (fixed params)", "hybrid (adaptive) [ours]", "auto (quality selector)"]


def table(df, methods):
    present = [c for c in COLS if c[0] in df.columns]
    head = "| Method | " + " | ".join(c[1] for c in present) + " |"
    sep = "|---|" + "---|" * len(present)
    lines = [head, sep]
    for m in methods:
        r = df[df["method"] == m]
        if r.empty:
            continue
        r = r.iloc[0]
        cells = []
        for k, _, nd in present:
            v = r.get(k)
            cells.append("–" if pd.isna(v) else f"{v:.{nd}f}")
        lines.append(f"| {m} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--team", default="TXX")
    ap.add_argument("--usns", default="USN1")
    ap.add_argument("--splits", nargs="+", default=["test_lol", "test_lolv2"])
    args = ap.parse_args()

    out = [args.usns, "", f"# Evaluation results — Problem P1 (Team {args.team})", ""]
    lock = ROOT / "results/test_lock.json"
    if lock.exists():
        lk = json.loads(lock.read_text())
        out.append(f"Frozen config `{Path(lk['config']).relative_to(ROOT).as_posix() if Path(lk['config']).is_absolute() else lk['config']}` (sha {lk['config_sha']}), weights sha {lk['weights_sha']}, "
                   f"git `{lk['git']}`, first test run {lk['time']}. All parameters were tuned on the "
                   "50-image validation split only; test sets were evaluated once.")
        out.append("")
    out.append("Metric order follows the problem statement: PSNR, SSIM, LPIPS, NIQE, latency, noise suppression "
               "and edge preservation. ↑ = higher is better, ↓ = lower is better. Numbers are generated by "
               "`scripts/evaluate.py` + `scripts/make_eval_md.py` and are not edited by hand.")
    out.append("")
    for sp in args.splits:
        f = ROOT / "results" / sp / "summary.csv"
        if not f.exists():
            out += [f"## {sp}", "", "_not evaluated_", ""]
            continue
        df = pd.read_csv(f)
        meta = json.loads((ROOT / "results" / sp / "meta.json").read_text())
        subset = df["subset"].iloc[0]
        out += [f"## {subset} ({meta['n_images']} images)", "", "### Comparison: classical vs. deep learning vs. hybrid", "",
                table(df, MAIN), "", "### Ablation (each row removes one component from the adaptive hybrid)", "",
                table(df, ["hybrid (adaptive) [ours]"] + [m for m in df["method"] if m.startswith("hybrid - ")]), ""]
    sel = ROOT / "results/selector_val.json"
    if sel.exists():
        s = json.loads(sel.read_text())
        out += ["## Quality-aware selector (validation, leave-one-out)", "",
                f"- Always hybrid: J = {s['always_hybrid']['J']:.4f}",
                f"- Selector (LOO): J = {s['selector_loo']['J']:.4f}, choices {s['selector_loo']['choice_counts']}",
                f"- Oracle (best per image): J = {s['oracle']['J']:.4f}",
                f"- Decision: **{s['decision']}**", ""]
    lat = ROOT / "results/deploy_latency.json"
    if lat.exists():
        d = json.loads(lat.read_text())
        meta, rows = (d.get("meta", {}), d["rows"]) if isinstance(d, dict) else ({}, d)
        out += [f"## Deployed latency ({meta.get('host', 'deployed CPU')})", ""]
        if meta.get("url"):
            out += [f"Live URL: {meta['url']}", ""]
        out += ["| Input size | Mode | Upload → result (s) | Processing in app (s) |", "|---|---|--:|--:|"]
        out += [f"| {r['size']} | {r['mode']} | {r['seconds']:.2f} | {r.get('processing_s', float('nan')):.2f} |" for r in rows]
        out += ["", f"Median of {rows[0].get('runs', 1)} runs each, warm instance, measured {meta.get('measured', '')}. "
                f"{meta.get('cold_start', '')}", ""]
    name = ROOT / f"eval_P1_{args.team}.md"
    name.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {name}")


if __name__ == "__main__":
    main()
